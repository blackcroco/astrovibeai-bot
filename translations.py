def get_text(language, key, **kwargs):
    """
    Returns a translated AstroVibe string.

    Falls back to French if the requested language
    or translation key does not exist.
    """

    if language not in TRANSLATIONS:
        language = "fr"

    text = TRANSLATIONS.get(
        language,
        TRANSLATIONS["fr"]
    ).get(
        key,
        TRANSLATIONS["fr"].get(key, key)
    )

    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, ValueError):
            pass

    return text
